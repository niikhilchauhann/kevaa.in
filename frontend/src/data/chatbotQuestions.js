// Function to find matching questions based on keywords
export const findMatchingQuestion = (userInput) => {
  const input = userInput.toLowerCase();
  let bestMatch = null;
  let maxMatches = 0;

  for (const question of chatbotQuestions) {
    let matches = 0;
    for (const keyword of question.keywords) {
      if (input.includes(keyword.toLowerCase())) {
        matches++;
      }
    }

    // If we have matches and it's better than previous best
    if (matches > maxMatches && matches >= 1) {
      maxMatches = matches;
      bestMatch = question;
    }
  }

  return bestMatch;
};
